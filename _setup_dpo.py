# CONFIGURE MCP WITHOUT REMOVING EXISTING SERVERS

config = project / ".giga_agent" / "mcp.json"
config.parent.mkdir(parents=True, exist_ok=True)

if config.exists():
    backup = config.with_name(
        "mcp.json.backup-" + datetime.now().strftime("%Y%m%d-%H%M%S")
    )
    shutil.copy2(config, backup)
    settings = json.loads(config.read_text(encoding="utf-8-sig"))
    print("Backup:", backup)
else:
    settings = {}

settings.setdefault("mcpServers", {})["dpo_files"] = {
    "command": "cmd",
    "args": [
        "/c",
        "npx",
        "-y",
        "@modelcontextprotocol/server-filesystem",
        "--confine-roots",
        str(data)
    ]
}

config.write_text(
    json.dumps(settings, ensure_ascii=False, indent=2),
    encoding="utf-8"
)

print("\nSETUP COMPLETE")
